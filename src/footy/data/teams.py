"""Team-name normalisation across data sources.

Canonical names = Football-Data.co.uk names (our primary source). They are
consistent across seasons, ASCII-friendly and cover every season we use, so
Football-Data rows need no mapping and their match IDs stay stable.

Every other source has an alias table in config/team_aliases.yaml:

    understat:
      EPL:
        Manchester United: Man United
    openfootball:
      EPL:
        Manchester United FC: Man United

Tables are scoped per league to avoid cross-league collisions.

Bootstrapping aliases by hand for ~150 teams x 3 sources is error-prone, so
`propose_aliases` infers them from the fixtures themselves: two rows from two
sources that share league, season, date (+/- a day or two) and exact score
are probably the same match, so their team names "vote" for each other.
The true pairing wins by a wide margin; we accept it only when the vote is
decisive and report the rest for manual review. Manual entries in the YAML
always take precedence over proposals.
"""

from __future__ import annotations

import logging
from dataclasses import dataclass
from pathlib import Path

import pandas as pd
import yaml

from footy.config import CONFIG_DIR

log = logging.getLogger(__name__)

ALIASES_PATH = CONFIG_DIR / "team_aliases.yaml"
REFERENCE_SOURCE = "football_data"

AliasTable = dict[str, dict[str, dict[str, str]]]  # source -> league -> alias -> canonical


class UnmappedTeamError(ValueError):
    """A team name from a source has no entry in the alias table."""


# --- Loading / saving ------------------------------------------------------------


def load_aliases(path: Path = ALIASES_PATH) -> AliasTable:
    if not path.exists():
        return {}
    with path.open(encoding="utf-8") as fh:
        return yaml.safe_load(fh) or {}


def save_aliases(aliases: AliasTable, path: Path = ALIASES_PATH) -> None:
    ordered = {
        source: {
            league: dict(sorted(table.items(), key=lambda kv: (kv[1], kv[0])))
            for league, table in sorted(leagues.items())
        }
        for source, leagues in sorted(aliases.items())
    }
    header = (
        "# Source team name -> canonical (Football-Data.co.uk) name, per league.\n"
        "# Generated by `footy teams propose`, then reviewed. Manual edits are preserved.\n"
    )
    body = yaml.safe_dump(ordered, allow_unicode=True, sort_keys=False, width=120)
    path.write_text(header + body, encoding="utf-8")


# --- Applying --------------------------------------------------------------------


def to_canonical(
    df: pd.DataFrame,
    source: str,
    league: str,
    aliases: AliasTable | None = None,
) -> pd.DataFrame:
    """Return a copy of df with home_team/away_team mapped to canonical names.

    The original names are kept in home_team_raw / away_team_raw.
    Raises UnmappedTeamError listing *every* unknown name, so one run shows
    the full fix-up list.
    """
    out = df.copy()
    out["home_team_raw"] = out["home_team"]
    out["away_team_raw"] = out["away_team"]
    if source == REFERENCE_SOURCE:
        return out

    aliases = aliases if aliases is not None else load_aliases()
    table = aliases.get(source, {}).get(league, {})
    names = pd.concat([out["home_team"], out["away_team"]]).dropna().unique()
    unknown = sorted(set(names) - set(table))
    if unknown:
        raise UnmappedTeamError(
            f"{len(unknown)} {source} team name(s) for {league} not in {ALIASES_PATH.name}: "
            f"{unknown}. Run `footy teams propose --source {source} --league {league}`."
        )
    out["home_team"] = out["home_team"].map(table).astype("string")
    out["away_team"] = out["away_team"].map(table).astype("string")
    return out


# --- Proposing -------------------------------------------------------------------


@dataclass(frozen=True)
class AliasProposal:
    league: str
    alias: str
    canonical: str
    votes: int
    appearances: int
    runner_up: str | None
    runner_up_votes: int

    @property
    def confidence(self) -> float:
        return self.votes / self.appearances if self.appearances else 0.0

    def is_decisive(self, min_confidence: float, min_margin: float) -> bool:
        return (
            self.confidence >= min_confidence
            and self.votes >= min_margin * max(self.runner_up_votes, 1)
        )


def _played(df: pd.DataFrame) -> pd.DataFrame:
    cols = ["league", "season", "date", "home_team", "away_team", "home_goals", "away_goals"]
    return df.dropna(subset=["home_goals", "away_goals"])[cols]


def propose_aliases(
    reference: pd.DataFrame,
    other: pd.DataFrame,
    *,
    max_day_gap: int = 2,
) -> list[AliasProposal]:
    """Infer alias -> canonical pairs by matching fixtures on date and score.

    `reference` must already use canonical names (i.e. Football-Data rows).
    """
    ref, oth = _played(reference), _played(other)
    keys = ["league", "season", "home_goals", "away_goals"]
    pairs = oth.merge(ref, on=keys, suffixes=("_o", "_r"))
    pairs = pairs[(pairs["date_o"] - pairs["date_r"]).abs().dt.days <= max_day_gap]

    votes = pd.concat([
        pairs[["league", "home_team_o", "home_team_r"]].set_axis(["league", "alias", "canon"], axis=1),
        pairs[["league", "away_team_o", "away_team_r"]].set_axis(["league", "alias", "canon"], axis=1),
    ]).value_counts().rename("votes").reset_index()

    appearances = (
        pd.concat([oth[["league", "home_team"]].set_axis(["league", "alias"], axis=1),
                   oth[["league", "away_team"]].set_axis(["league", "alias"], axis=1)])
        .value_counts().rename("appearances")
    )

    proposals = []
    for (league, alias), grp in votes.groupby(["league", "alias"]):
        grp = grp.sort_values("votes", ascending=False)
        best = grp.iloc[0]
        second = grp.iloc[1] if len(grp) > 1 else None
        proposals.append(AliasProposal(
            league=league,
            alias=alias,
            canonical=best["canon"],
            votes=int(best["votes"]),
            appearances=int(appearances.get((league, alias), 0)),
            runner_up=None if second is None else second["canon"],
            runner_up_votes=0 if second is None else int(second["votes"]),
        ))
    return proposals


def merge_proposals(
    aliases: AliasTable,
    source: str,
    proposals: list[AliasProposal],
    *,
    min_confidence: float = 0.8,
    min_margin: float = 3.0,
) -> tuple[AliasTable, list[AliasProposal], list[AliasProposal]]:
    """Add decisive proposals to the table without overwriting existing entries.

    Returns (updated table, accepted, needs_review).
    """
    updated: AliasTable = {s: {lg: dict(t) for lg, t in lgs.items()} for s, lgs in aliases.items()}
    table = updated.setdefault(source, {})
    accepted, review = [], []
    for p in proposals:
        league_table = table.setdefault(p.league, {})
        if p.alias in league_table:
            if league_table[p.alias] != p.canonical:
                log.warning("Existing alias %s/%s -> %s disagrees with proposal %s (kept existing)",
                            p.league, p.alias, league_table[p.alias], p.canonical)
            continue
        if p.is_decisive(min_confidence, min_margin):
            league_table[p.alias] = p.canonical
            accepted.append(p)
        else:
            review.append(p)

    # Sanity: within a league two aliases may map to one canonical name (club renames),
    # but log it so a reviewer can confirm it is a rename and not a mistake.
    for league, league_table in table.items():
        inverse: dict[str, list[str]] = {}
        for alias, canon in league_table.items():
            inverse.setdefault(canon, []).append(alias)
        for canon, names in inverse.items():
            if len(names) > 1:
                log.info("%s/%s: several %s aliases map to %s: %s", source, league, source,
                         canon, names)
    return updated, accepted, review


def coverage_report(reference: pd.DataFrame, other_canonical: pd.DataFrame) -> pd.DataFrame:
    """After mapping: per season, what share of reference matches the other source
    contains (joined on league/season/home/away) and how often scores agree."""
    ref = _played(reference)
    oth = _played(other_canonical)
    joined = ref.merge(oth, on=["league", "season", "home_team", "away_team"],
                       how="left", suffixes=("", "_o"), indicator=True)
    joined["found"] = joined["_merge"] == "both"
    joined["score_agrees"] = (
        (joined["home_goals"] == joined["home_goals_o"])
        & (joined["away_goals"] == joined["away_goals_o"])
    )
    joined["day_gap"] = (joined["date"] - joined["date_o"]).abs().dt.days
    return joined.groupby(["league", "season"]).agg(
        matches=("found", "size"),
        found_pct=("found", lambda s: 100 * s.mean()),
        score_agree_pct=("score_agrees", lambda s: 100 * s[joined.loc[s.index, "found"]].mean()),
        max_day_gap=("day_gap", "max"),
    )
